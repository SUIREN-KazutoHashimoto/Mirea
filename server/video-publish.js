import { copyFile, rename, unlink, stat, rm, readdir, open } from 'node:fs/promises';
import { join } from 'node:path';
import { transaction } from './database.js';
import {attachUploadSeries} from './upload-series.js';
import { removeItemDirectory } from './media.js';
import { probeVideo } from './video-transcode.js';

// Filesystem publication precedes the atomic database commit. Until that commit
// no API can see these files. The original stays in staging (and in verified
// transfer parts) throughout: recovery can safely regenerate incomplete outputs.
export async function publishVideo(context,upload,authorize) {
  const {db,media,videoTranscoder,uploadDir,stagingDir,thumbnailDir,videoDir,originalDir,previewDir,publicItem}=context;
  const {id,shelf_id:shelfId,user_id:userId,title}=upload,first=JSON.parse(upload.files_json)[0];
  const stage=join(stagingDir,id),work=join(stage,'video'),final=join(videoDir,id);
  const canonical=join(uploadDir,id),thumbnail=join(thumbnailDir,`${id}.jpg`),preview=join(previewDir,`${id}.mp4`),original=join(originalDir,id);
  const existing=db.prepare('SELECT * FROM items WHERE id=?').get(id);
  if(existing)return publicItem(existing);
  const report=value=>db.prepare('UPDATE upload_sessions SET processing_json=? WHERE id=?').run(JSON.stringify(value),id);
  try {
    // Only generated outputs, never raw-1, are replaced on retry.
    if(!/^[0-9a-f-]{36}$/.test(id))throw new Error('Invalid video job ID');
    await rm(work,{recursive:true,force:true});
    const metadata=await videoTranscoder.convert(join(stage,'raw-1'),work,{authorize,report});
    report({stage:'thumbnail',percent:0});
    await media.thumbnail(join(work,`${metadata.renditions[0].quality}.mp4`),'video/mp4',join(work,'thumbnail.jpg'));
    await media.preview(join(work,`${metadata.renditions[0].quality}.mp4`),join(work,'preview.mp4'),'video/mp4');
    for(const name of ['thumbnail.jpg','preview.mp4'])if(!(await stat(join(work,name))).size)throw new Error('Missing video thumbnail');
    await media.validateImage(join(work,'thumbnail.jpg'));
    const previewInfo=await probeVideo(join(work,'preview.mp4'));
    if(previewInfo.video.codec_name!=='h264'||previewInfo.audio||previewInfo.duration>6.25)throw new Error('Invalid generated video preview');
    authorize();report({stage:'publish',percent:100});
    await removeItemDirectory(videoDir,id);
    await rename(work,final);
    await Promise.all([canonical,thumbnail,preview,original].map(path=>unlink(path).catch(error=>{if(error.code!=='ENOENT')throw error;})));
    await copyFile(join(final,`${metadata.renditions[0].quality}.mp4`),canonical);
    await copyFile(join(final,'thumbnail.jpg'),thumbnail);
    await copyFile(join(final,'preview.mp4'),preview);
    // Keeping a distinct copy makes the user's retention choice explicit. No
    // legacy asset/original is visited or rewritten by this new-upload path.
    if(upload.retain_original)await copyFile(join(stage,'raw-1'),original);
    if((await stat(canonical)).size!==metadata.renditions[0].size||upload.retain_original&&(await stat(original)).size!==first.size)throw new Error('Published file size mismatch');
    // Flush generated bytes before the commit that authorizes source removal.
    for(const path of [...(await readdir(final)).map(name=>join(final,name)),canonical,thumbnail,preview,...(upload.retain_original?[original]:[])]){
      const handle=await open(path,'r+');try{await handle.sync();}finally{await handle.close();}
    }
    if(process.platform!=='win32')for(const path of [final,videoDir,uploadDir,thumbnailDir,previewDir,originalDir]){
      const handle=await open(path,'r');try{await handle.sync();}finally{await handle.close();}
    }
    authorize();
    metadata.originalFilename=first.filename;
    transaction(db,()=>{
      db.prepare(`INSERT INTO items(id,shelf_id,title,filename,mime_type,size,uploaded_by,created_at,page_count,thumbnail_ready)
        VALUES(?,?,?,?, 'video/mp4',?,?,?,1,1)`).run(id,shelfId,title,first.filename.replace(/\.[^.]+$/,'')+'.mp4',metadata.renditions[0].size,userId,Date.now());
      db.prepare('INSERT INTO video_assets VALUES(?,?,?)').run(id,JSON.stringify(metadata),upload.retain_original?1:0);
      attachUploadSeries(db,upload);
      db.prepare("UPDATE upload_sessions SET state='complete',error=NULL,processing_json=? WHERE id=?").run(JSON.stringify({stage:'complete',percent:100}),id);
    });
    // The caller now discards source staging + transfer parts. If interrupted,
    // startup cleans complete sessions only after observing the durable commit.
    return publicItem(db.prepare('SELECT * FROM items WHERE id=?').get(id));
  }catch(error){
    if(!db.prepare('SELECT 1 FROM items WHERE id=?').get(id))await Promise.allSettled([
      removeItemDirectory(videoDir,id),...[canonical,thumbnail,preview,original].map(path=>unlink(path))
    ]);
    throw error;
  }
}
